// JavaScript String Functions

let str = "Sachin Rajput";

console.log("Original String:", str);

// indexOf()
console.log("indexOf('Rajput'):", str.indexOf("Rajput"));

// lastIndexOf()
console.log("lastIndexOf('a'):", str.lastIndexOf("a"));

// concat()
let str2 = " Kumar";
console.log("concat():", str.concat(str2));

// slice()
console.log("slice(0, 6):", str.slice(0, 6));

// substr()
console.log("substr(7, 6):", str.substr(7, 6));

// toUpperCase()
console.log("Uppercase:", str.toUpperCase());

// toLowerCase()
console.log("Lowercase:", str.toLowerCase());